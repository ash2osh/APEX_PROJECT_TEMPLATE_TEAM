"""Opt-in checks of `baseline` against two disposable Oracle databases.

These run the real `scripts/team.sh baseline` commands in a copy of this repository: `export-source`, `export-data`
and `build` (with `--data` and with `--bundle`), reading a seeded DEV schema and a seeded staging schema. Every object
they create is named `BLT<token>_...` and is dropped at the end. CI never runs them: the module is skipped unless the
variables of tests/test_live_feature_release.py are set, with the staging variable required (a build compares two
environments, so the staging profile must point at a separate database such as a Docker container):

    TEMPLATE_LIVE_DISPOSABLE=1
    TEMPLATE_LIVE_CONNECTION=<name>          DEV: a saved SQLcl connection that logs in as the schema
    TEMPLATE_LIVE_SCHEMA=<SCHEMA>            the disposable schema, which must be that login's user
    TEMPLATE_LIVE_STAGING_CONNECTION=<name>  staging: a saved connection to a separate database, same schema name

`export-grants` is not covered: its system-privilege part needs a DBA login, which these runs never use.
See docs/baseline.md ("Live check") for the procedure and what each check shows.
"""

